MAX_FILE=1024*1024
MAX_TOTAL=8*1024*1024
MAX_JSON=4*1024*1024


def bounded(path,limit=MAX_JSON):
    with Path(path).open('rb') as stream:data=stream.read(limit+1)
    if len(data)>limit:raise ValueError('File reading bound exceeded')
    return data


def read_json(path):return json.loads(bounded(path))
def sha(data):return hashlib.sha256(data).hexdigest()


def read_blob(path,oid,remaining=MAX_TOTAL):
    size=int(git(path,'cat-file','-s',oid).strip())
    if size>MAX_FILE or size>remaining:raise ValueError('Git blob reading bound exceeded')
    data=git(path,'cat-file','blob',oid)
    if len(data)!=size:raise ValueError('Git blob changed while reading')
    return data


def dispositions(signals):
    result=[]
    for kind in ('generated','vendor'):
        for signal in signals[kind]:
            text=signal['text']
            if kind=='generated' and '@param autoUsage' in text and 'automatically generated usage statement' in text:
                decision='HELP_TEXT_OUTPUT_NOT_GENERATED_SOURCE'
            elif kind=='generated' and 'default style as generated by the default Builder' in text:
                decision='BUILDER_OUTPUT_NOT_GENERATED_SOURCE'
            else:raise ValueError('Unresolved source-content signal requires explicit review')
            result.append(dict(kind=kind,line=signal['line'],decision=decision))
    return result


def license_evidence(repository_id,path,oid,data):
    text=data.decode('utf-8',errors='strict')
    expected={'apache/commons-cli':'Apache-2.0','pallets/click':'BSD-3-Clause','adamchainz/django-browser-reload':'MIT'}[repository_id]
    markers={
        'Apache-2.0':('Apache License','Version 2.0'),
        'BSD-3-Clause':('Redistribution and use in source and binary forms','Neither the name'),
        'MIT':('Permission is hereby granted, free of charge','THE SOFTWARE IS PROVIDED'),
    }
    if 'NOTICE' in Path(path).name:
        role='ATTRIBUTION_NOTICE';detected=None
    else:
        if not all(v in text for v in markers[expected]):raise ValueError('Expected license text not established')
        role='ROOT_LICENSE';detected=expected
    return dict(path=path,git_object_id=oid,sha256=sha(data),bytes=len(data),role=role,
                detected_license=detected,ownership_or_project_permission_certified=False)


def embedded_analyzer_rights(cached,published_runtime):
    evidence=[]
    actual={p['filename']:p for p in published_runtime['plugins']}
    for row in cached:
        text=row['private_text'];raw=text.encode()
        if sha(raw)!=row['sha256'] or not text.startswith('SONAR Source-Available License v1.0\n'):
            raise ValueError('Embedded license cache digest/version mismatch')
        if 'artificial intelligence technology' not in text or 'Non-competitive Purpose' not in text:
            raise ValueError('Expected license restriction not established')
        evidence.append(dict(plugin=row['plugin'],jar_sha256=actual[row['plugin']]['sha256'],
            license_path=row['path'],license_sha256=row['sha256'],license_version='SSAL-1.0',license_date='2024-11-13',
            external_ai_restriction_identified=True,permission_for_planned_ai_use='NOT_ESTABLISHED',
            provenance='Cached offline extraction from interrupted Phase5.2.2; bytes rehashed, no container access in Task A',
            independent_reextraction_this_task=False))
    if len(evidence)!=3 or len({v['plugin'] for v in evidence})!=3:raise ValueError('Three pinned analyzer license records required')
    return evidence


def review(base,cache_path,license_cache):
    configs=read_json(base/'examples/phase5_2/replay_sources.example.json')
    compressed=bounded(base/'examples/phase5_2_1/source_inventory.json.gz')
    with gzip.GzipFile(fileobj=__import__('io').BytesIO(compressed)) as stream:
        raw=stream.read(MAX_JSON+1)
    if len(raw)>MAX_JSON:raise ValueError('Inventory decompression bound exceeded')
    frozen=json.loads(raw);cached=read_json(cache_path)
    if frozen['version']!=VERSION or cached['version']!=VERSION:raise ValueError('Scope version mismatch')
    registrations=read_json(base/'examples/phase5_2_1/registrations.json')['registrations']
    for registration in registrations:validate_registration(registration)
    expected_states={(s['repository_id'],s['commit_sha']):s for s in frozen['source_states']}
    cached_states={(s['repository_id'],s['commit_sha']):s for s in cached['source_states']}
    if len(expected_states)!=18 or set(cached_states)!=set(expected_states):raise ValueError('All eighteen frozen states required')
    checked={};source_bytes=0;license_blobs={};states=[]
    for config in sorted(configs,key=lambda v:v['repository_id']):
        lineage=ScopedGit(GitArchive(config['path'],config['tip_sha'],config['ref_observed_utc']),config['repository_id'])
        for key,state in expected_states.items():
            if key[0]!=config['repository_id']:continue
            active=lineage.state(state['cutoff_utc'])
            if active.sha!=state['commit_sha'] or active.tree!=state['tree_sha']:raise ValueError('Frozen state/cutoff/tree mismatch')
            inv=lineage.inventory(active.sha)
            if inv!=state['inventory'] or inv['blockers']:raise ValueError('Exact frozen production inventory mismatch')
            cache=cached_states[key]
            files={v['path']:v for v in cache['files']}
            paths=[v['path'] for v in inv['entries'] if v['role']!='OUTSIDE_ROOT']
            if paths!=cache['reviewed_paths'] or set(paths)!=set(files) or cache['inventory_id']!=inv['inventory_id']:
                raise ValueError('Incomplete cached content review')
            records=[]
            for entry in inv['entries']:
                if entry['role']=='OUTSIDE_ROOT':continue
                old=files[entry['path']]
                if any(old[k]!=entry[k] for k in entry):raise ValueError('Cached source identity mismatch')
                oid=entry['git_object_id']
                facts={k:old[k] for k in ('sha256','bytes','lines','signals')}
                if oid not in checked:
                    # Revalidate bytes once per immutable blob; reuse cached signals
                    # and content hashes across all other paths/states.
                    data=read_blob(config['path'],oid,MAX_TOTAL-source_bytes);source_bytes+=len(data)
                    if len(data)>MAX_FILE or source_bytes>MAX_TOTAL:raise ValueError('Source-content byte bound exceeded')
                    if sha(data)!=old['sha256'] or len(data)!=old['bytes']:raise ValueError('Cached blob content mismatch')
                    data.decode('utf-8',errors='strict')
                    if b'\0' in data:raise ValueError('Binary content in production root')
                    checked[oid]=facts
                elif checked[oid]!=facts:raise ValueError('Conflicting review for identical Git blob')
                records.append(dict(path=entry['path'],git_object_id=oid,sha256=old['sha256'],role=entry['role'],
                    language=entry['language'],signal_dispositions=dispositions(old['signals']),attribution_header_detected=bool(old['signals']['copyright'])))
            licenses=[]
            by_path={v['path']:v for v in inv['entries']}
            for path in config['license_paths']:
                if path not in by_path:continue
                oid=by_path[path]['git_object_id']
                if oid not in license_blobs:
                    data=read_blob(config['path'],oid,MAX_TOTAL-source_bytes-sum(len(v) for v in license_blobs.values()))
                    license_blobs[oid]=data
                licenses.append(license_evidence(config['repository_id'],path,oid,license_blobs[oid]))
            if not any(v['role']=='ROOT_LICENSE' for v in licenses):raise ValueError('Pinned root license unavailable')
            states.append(dict(repository_id=key[0],family_id=state['family_id'],cutoff_utc=state['cutoff_utc'],
                commit_sha=active.sha,tree_sha=active.tree,scope_id=inv['scope_id'],inventory_id=inv['inventory_id'],
                native_project_key_plan=state['native_project_key_plan'],tracked_files=len(inv['entries']),
                role_counts=dict(sorted(Counter(v['role'] for v in inv['entries']).items())),
                production_files_by_language=dict(sorted(Counter(v['language'] for v in records if v['role']=='PRODUCTION').items())),
                outside_root_extensions=dict(sorted(Counter(Path(v['path']).suffix.lower() or '<none>' for v in inv['entries'] if v['role']=='OUTSIDE_ROOT').items())),
                content_records=records,license_records=licenses,
                static_content_status='VERIFIED_NO_UNRESOLVED_RECORDED_SIGNALS',
                content_review_limitations=['Static source inspection is not independent proof of ownership or absence of all copied code','Native NCLOC and analyzer completeness not measured'],
                operational_admission_status='QUARANTINE_UNCHANGED',legal_acceptance=False))
    readiness={str(p.relative_to(base)):dict(sha256=sha(bounded(p)),data=read_json(p)) for p in sorted((base/'examples').rglob('*readiness*.json'))}
    analyzer=embedded_analyzer_rights(read_json(license_cache),read_json(base/'examples/phase5_2_1/runtime_artifact_inspection.json'))
    return dict(version='phase5_2_2_a-source-rights-v1',scope_version=VERSION,task_status='PASS_REVIEW_COMPLETE',
        rights_status='BLOCKED_PENDING_HUMAN_REVIEW_OR_PERMISSION',collection_status='BLOCKED',task_b_authorized=False,
        unique_in_root_blobs_verified=len(checked),unique_in_root_bytes_verified=source_bytes,
        unique_root_license_notice_blobs=len(license_blobs),states=states,analyzer_licenses=analyzer,
        inputs=dict(cached_content_sha256=sha(bounded(cache_path)),cached_analyzer_license_sha256=sha(bounded(license_cache)),
            frozen_source_inventory_sha256=sha(compressed),readiness={k:{'sha256':v['sha256'],'status':v['data'].get('overall_status',v['data'].get('status'))} for k,v in readiness.items()}),
        human_approvals=[dict(id=k,status='NOT_APPROVED',decision_owner=owner) for k,owner in (
            ('ANALYZER_EXTERNAL_AI_USE_OR_WRITTEN_PERMISSION','Project owner and qualified legal/licensor review'),
            ('SONAR_DERIVED_DATA_PUBLICATION_POLICY','Project owner/institution; licensor clarification where necessary'),
            ('SOURCE_NOTICE_AND_DATASET_ATTRIBUTION_PLAN','Project owner/institution'),
            ('RUNTIME_CREDENTIAL_AND_EXECUTION_PERMISSIONS','Operator in a separately authorized runtime task'))],
        forbidden_operations_executed=dict(containers=0,maven=0,models=0,scans=0,dependency_acquisition=0),
        process_peak_rss_kib=resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--content-cache',required=True);parser.add_argument('--analyzer-license-cache',required=True);parser.add_argument('--output',required=True);a=parser.parse_args(argv)
    output=Path(a.output)
    if output.exists():raise ValueError('Refusing overwrite')
    result=review(Path(__file__).resolve().parents[1],Path(a.content_cache),Path(a.analyzer_license_cache))
    output.write_bytes(canonical(result)+b'\n')
    print('Verified eighteen frozen states; unique source blobs:',result['unique_in_root_blobs_verified'],'peak RSS KiB:',result['process_peak_rss_kib'])


if __name__=='__main__':main()
