"""Read-only identity of already installed numerical dependencies; no acquisition."""
import base64
import hashlib
from importlib.metadata import distribution
from pathlib import Path
import sys
from forecasting_research.phase6_0.artifacts import sha
from forecasting_research.phase6_0.contracts import digest


def identity():
    dist = distribution('numpy')
    if dist.version != '2.4.4':
        raise ValueError('Existing pinned NumPy 2.4.4 required, no substitutions')
    files = {}
    for entry in dist.files:
        if entry.hash is None:
            continue  # Generated bytecode/RECORD are not claimed as signed payloads.
        if entry.hash.mode != 'sha256':
            raise ValueError('Unexpected installed artifact hash mode')
        path = Path(dist.locate_file(entry))
        value = sha(path)
        if base64.urlsafe_b64encode(bytes.fromhex(value)).rstrip(b'=').decode() != entry.hash.value:
            raise ValueError('Installed NumPy RECORD mismatch: '+str(entry))
        files[str(entry)] = value
    return dict(numpy_version=dist.version, recorded_files=len(files), files=files,
                canonical_files_sha256=digest(files), python_version=sys.version,
                python_binary_sha256=sha(Path(sys.executable)),
                provenance='Existing local environment and installed RECORD, not independent publisher signature')
